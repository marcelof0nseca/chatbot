-- =====================================================================
-- Tino - assistente de atendimento (WXN)
-- Esquema do banco de dados - versao 2
--
-- Alinhado ao modelo de classes em com.nxn.chatbot.dominio:
-- chave primaria BIGINT de identidade, enums como VARCHAR com CHECK,
-- carimbos de tempo em todas as tabelas de entidade.
--
-- Compativel com H2 2.x (desenvolvimento) e PostgreSQL 16+ (producao).
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. CLIENTE - quem fala com o Tino pelo WhatsApp
--    O e-mail e opcional: quem chega pelo WhatsApp so informa o telefone.
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR(120) NOT NULL,
    telefone       VARCHAR(20)  NOT NULL,
    email          VARCHAR(160),
    tipo           VARCHAR(10)  NOT NULL,
    criado_em      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cliente PRIMARY KEY (id),
    CONSTRAINT uk_cliente_telefone UNIQUE (telefone),
    CONSTRAINT ck_cliente_tipo CHECK (tipo IN ('EXTERNO', 'INTERNO'))
);

-- ---------------------------------------------------------------------
-- 2. CONSENTIMENTO - historico de aceite do aviso de privacidade (LGPD)
--    Tabela propria, e nao coluna em cliente, porque o titular pode
--    revogar e aceitar de novo, e a trilha precisa ficar guardada.
-- ---------------------------------------------------------------------
CREATE TABLE consentimento (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    cliente_id       BIGINT      NOT NULL,
    versao_politica  VARCHAR(20) NOT NULL,
    aceito_em        TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revogado_em      TIMESTAMP,
    CONSTRAINT pk_consentimento PRIMARY KEY (id),
    CONSTRAINT fk_consentimento_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);
CREATE INDEX ix_consentimento_cliente ON consentimento (cliente_id, aceito_em);

-- ---------------------------------------------------------------------
-- 3. ATENDENTE - usuario do painel (atendente ou gestor)
-- ---------------------------------------------------------------------
CREATE TABLE atendente (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR(120) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    senha_hash     VARCHAR(100) NOT NULL,
    perfil         VARCHAR(10)  NOT NULL,
    disponivel     BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_atendente PRIMARY KEY (id),
    CONSTRAINT uk_atendente_email UNIQUE (email),
    CONSTRAINT ck_atendente_perfil CHECK (perfil IN ('ATENDENTE', 'GESTOR'))
);

-- ---------------------------------------------------------------------
-- 4. ARTIGO_CONHECIMENTO - a base que o gestor edita pelo painel
--    publico = TRUE responde a qualquer um; FALSE so a colaborador interno.
--    ativo = FALSE tira o artigo de circulacao sem apagar o historico.
-- ---------------------------------------------------------------------
CREATE TABLE artigo_conhecimento (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    pergunta        VARCHAR(300)  NOT NULL,
    resposta        VARCHAR(4000) NOT NULL,
    categoria       VARCHAR(60)   NOT NULL,
    publico         BOOLEAN       NOT NULL DEFAULT TRUE,
    ativo           BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_por  BIGINT,
    CONSTRAINT pk_artigo PRIMARY KEY (id),
    CONSTRAINT fk_artigo_atendente FOREIGN KEY (atualizado_por) REFERENCES atendente (id)
);
CREATE INDEX ix_artigo_busca ON artigo_conhecimento (ativo, publico);

-- ---------------------------------------------------------------------
-- 5. ARTIGO_VARIACAO - outras formas de fazer a mesma pergunta
-- ---------------------------------------------------------------------
CREATE TABLE artigo_variacao (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    artigo_id  BIGINT       NOT NULL,
    texto      VARCHAR(300) NOT NULL,
    CONSTRAINT pk_artigo_variacao PRIMARY KEY (id),
    CONSTRAINT fk_variacao_artigo FOREIGN KEY (artigo_id) REFERENCES artigo_conhecimento (id),
    CONSTRAINT uk_variacao UNIQUE (artigo_id, texto)
);

-- ---------------------------------------------------------------------
-- 6. CONVERSA - agregado central. A coluna contexto guarda o estado de
--    trabalho do dialogo entre uma mensagem e outra (secao 4 do
--    documento modelo-de-dados.md).
-- ---------------------------------------------------------------------
CREATE TABLE conversa (
    id                      BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    cliente_id              BIGINT        NOT NULL,
    canal                   VARCHAR(20)   NOT NULL DEFAULT 'WHATSAPP',
    estado                  VARCHAR(30)   NOT NULL,
    contexto                VARCHAR(8000),
    tentativas_sem_sucesso  SMALLINT      NOT NULL DEFAULT 0,
    iniciada_em             TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultima_atividade_em     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    encerrada_em            TIMESTAMP,
    expurgo_previsto_para   TIMESTAMP,
    CONSTRAINT pk_conversa PRIMARY KEY (id),
    CONSTRAINT fk_conversa_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT ck_conversa_estado CHECK (estado IN (
        'AGUARDANDO_CONSENTIMENTO', 'COM_BOT', 'AGUARDANDO_ATENDENTE',
        'COM_ATENDENTE', 'ENCERRADA')),
    CONSTRAINT ck_conversa_canal CHECK (canal IN ('WHATSAPP', 'WEB'))
);
CREATE INDEX ix_conversa_cliente ON conversa (cliente_id, iniciada_em);
CREATE INDEX ix_conversa_estado ON conversa (estado, ultima_atividade_em);
CREATE INDEX ix_conversa_expurgo ON conversa (expurgo_previsto_para);

-- ---------------------------------------------------------------------
-- 7. MENSAGEM - cada fala da conversa. Nunca sofre UPDATE nem DELETE
--    individual: historico de atendimento nao se reescreve.
--
--    O autor e polimorfico: tipo_remetente diz a origem e remetente_id
--    aponta para cliente ou atendente (fica nulo quando e o bot).
--
--    id_externo guarda o identificador da mensagem no WhatsApp e e UNIQUE
--    porque a Meta reenvia o webhook quando nao recebe 200 - sem isso a
--    mesma mensagem entraria duas vezes.
-- ---------------------------------------------------------------------
CREATE TABLE mensagem (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    conversa_id     BIGINT        NOT NULL,
    tipo_remetente  VARCHAR(10)   NOT NULL,
    remetente_id    BIGINT,
    conteudo        VARCHAR(4000) NOT NULL,
    data_hora       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_externo      VARCHAR(80),
    artigo_id       BIGINT,
    confianca       NUMERIC(4,3),
    CONSTRAINT pk_mensagem PRIMARY KEY (id),
    CONSTRAINT fk_mensagem_conversa FOREIGN KEY (conversa_id) REFERENCES conversa (id),
    CONSTRAINT fk_mensagem_artigo FOREIGN KEY (artigo_id) REFERENCES artigo_conhecimento (id),
    CONSTRAINT uk_mensagem_id_externo UNIQUE (id_externo),
    CONSTRAINT ck_mensagem_remetente CHECK (tipo_remetente IN ('CLIENTE', 'CHATBOT', 'ATENDENTE')),
    CONSTRAINT ck_mensagem_confianca CHECK (confianca IS NULL OR (confianca >= 0 AND confianca <= 1))
);
CREATE INDEX ix_mensagem_conversa ON mensagem (conversa_id, data_hora);

-- ---------------------------------------------------------------------
-- 8. TICKET - o atendimento humano aberto no escalonamento
-- ---------------------------------------------------------------------
CREATE TABLE ticket (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    conversa_id   BIGINT      NOT NULL,
    atendente_id  BIGINT,
    motivo        VARCHAR(25) NOT NULL,
    status        VARCHAR(15) NOT NULL,
    aberto_em     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assumido_em   TIMESTAMP,
    encerrado_em  TIMESTAMP,
    CONSTRAINT pk_ticket PRIMARY KEY (id),
    CONSTRAINT uk_ticket_conversa UNIQUE (conversa_id),
    CONSTRAINT fk_ticket_conversa FOREIGN KEY (conversa_id) REFERENCES conversa (id),
    CONSTRAINT fk_ticket_atendente FOREIGN KEY (atendente_id) REFERENCES atendente (id),
    CONSTRAINT ck_ticket_motivo CHECK (motivo IN (
        'BAIXA_CONFIANCA', 'SOLICITACAO_CLIENTE', 'ASSUNTO_NAO_SUPORTADO',
        'FORA_DO_EXPEDIENTE', 'TENTATIVAS_ESGOTADAS')),
    CONSTRAINT ck_ticket_status CHECK (status IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO'))
);
CREATE INDEX ix_ticket_fila ON ticket (status, aberto_em);
CREATE INDEX ix_ticket_atendente ON ticket (atendente_id, status);

-- ---------------------------------------------------------------------
-- 9. HORARIO_ATENDIMENTO - uma linha por dia da semana (1 = segunda)
-- ---------------------------------------------------------------------
CREATE TABLE horario_atendimento (
    id          BIGINT   GENERATED BY DEFAULT AS IDENTITY,
    dia_semana  SMALLINT NOT NULL,
    atende      BOOLEAN  NOT NULL DEFAULT TRUE,
    abre        TIME,
    fecha       TIME,
    CONSTRAINT pk_horario PRIMARY KEY (id),
    CONSTRAINT uk_horario_dia UNIQUE (dia_semana),
    CONSTRAINT ck_horario_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_horario_faixa CHECK (atende = FALSE OR (abre IS NOT NULL AND fecha IS NOT NULL AND abre < fecha))
);

-- ---------------------------------------------------------------------
-- 10. FERIADO - nacionais importados por tarefa anual, locais na mao
-- ---------------------------------------------------------------------
CREATE TABLE feriado (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    data_feriado   DATE         NOT NULL,
    descricao      VARCHAR(120) NOT NULL,
    origem         VARCHAR(10)  NOT NULL,
    importado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_feriado PRIMARY KEY (id),
    CONSTRAINT uk_feriado_data UNIQUE (data_feriado),
    CONSTRAINT ck_feriado_origem CHECK (origem IN ('NACIONAL', 'MANUAL'))
);
CREATE INDEX ix_feriado_data ON feriado (data_feriado);
